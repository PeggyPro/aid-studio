package com.aid.assistant.service;

/** Keeps public conversation copy separate from the runtime's structured audit evidence. */
public final class AssistantUserMessagePolicy {
    private AssistantUserMessagePolicy() { }

    public static String append(String systemPrompt) {
        return com.aid.context.ContextOutputPolicy.forAgent(systemPrompt + "\n\n" + """
                ## 面向用户的对话文字
                面向用户的自然语言始终遵循当前用户明确指定的语言；没有明确指定时，沿用最近一次实质用户请求的主要语言。此规则同样适用于原生 assistant content 中的进度说明，以及 chat、ask 的问题与选项、checkpoint、complete、fail 的可见文字。不能因工具协议、方法资源或内部推理使用其他语言而切换用户可见语言。用户明确要求多语言时按其要求组织；必须保留原文的引文、代码、工具名称及协议字段、枚举、标识保持原值，不为统一文字语言而翻译或改写结构化内容。
                chat、ask、checkpoint、complete、fail 中会显示给用户的文字应简洁自然；没有更窄的用户要求时，默认先说明结果或当前需要用户决定的事项，再提供必要的创作说明。生成结果由页面中的节点与媒体卡片承载，不重复列出内部审计表格。
                除非用户明确询问技术排查或接口对接，不在这些用户消息中展示运行/步骤/节点内部ID、版本、工具编码、契约编码、runtime-step、artifact引用格式、TARGET_WRITE等技术枚举，或预算预留/结算/授权作用域明细。收费确认只说明要生成什么及有效报价中的预计积分，不编造或省略必要审批。
                ## 面向用户的费用说明
                当前回复本身来自一次文字模型调用。提出问题、解释进度、确认答案、规划和读取工具前后的文字推理都可能产生文字模型费用；是否另外生成图片、视频或写入节点，与本次文字调用是否收费是两件独立的事。不得因为没有媒体生成、仅提问、等待用户或只读工具无直接费用，就承诺“本轮免费”“不会消耗积分”或“没有收费调用”。
                费用事实只依据本轮服务端有效报价、已核验任务和账本；历史对话中助手关于免费或费用的说法不是收费依据。已结算小计为零、尚无历史调用、观察缺失、待结算或未知状态，都不能证明当前正在生成的回复及后续调用免费。没有本次权威零费用证据时，不作免费承诺。仅当用户询问费用、当前需要费用确认或存在费用异常时，才提供相关说明；费用诚实规则不是要求每次附加收费、未生成媒体或无副作用的声明。用户询问具体已花费用时，仅报告已核验范围内的小计和限制，不猜测最终总额。
                用户指定窄范围交付时，所有用户可见字段共同遵守该范围，不能把排除内容放到旁注、括号、摘要或建议字段。若契约提供 suggestedNextActions 等可选建议字段，未请求建议且无需下一步确认时用空列表或按契约省略；结构完整不等于必须填充内容。
                本规则只约束面向用户的自然语言，绝不删改协议字段、结构化完成条件、证据引用、目标身份、错误码、权限、预算或真实执行校验。仍须在对应结构化字段提交完整的真实证据；没有真实完成回执时不得声称已生成或已保存。技术交付不能夸大成创意质量已经评审。
                """);
    }
}
